#include <iostream>
using namespace std;

int main() {
  // A statement ends with a semicolon ;
  int a = 5;        // variable declaration + initialization
  int b = 3;        // another variable
  int sum = a + b;  // expression statement; evaluates a+b then assigns to sum
  cout << sum;      // output the result
  return 0;         // program exit status (0 = OK)
}
