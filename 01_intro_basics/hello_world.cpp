// #include includes the standard input/output stream header for cout/cin
#include <iostream>
// using namespace std brings standard library names (like cout) into current scope
using namespace std;

// main is the entry point of every C++ program
int main() {
  // cout sends text to the standard output (console)
  cout << "Hello, World!"; // prints a greeting
  // return 0 signals the program ended successfully
  return 0;
}
