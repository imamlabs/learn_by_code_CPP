// Fungsi matematika lain
#include <iostream>
#include <cmath>
using namespace std;

int main() {
  cout << floor(3.7) << "\n";  // pembulatan ke bawah
  cout << ceil(3.1) << "\n";   // pembulatan ke atas
  cout << fabs(-8.5) << "\n";  // nilai absolut
  cout << fmin(2.0, 5.0) << "\n"; // minimum
  cout << fmax(2.0, 5.0) << "\n"; // maksimum
  return 0;
}
