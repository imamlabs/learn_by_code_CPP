// Menampilkan ukuran tipe data
#include <iostream>
using namespace std;

int main() {
  cout << "sizeof(int): " << sizeof(int) << "\n";         // ukuran int
  cout << "sizeof(double): " << sizeof(double) << "\n";   // ukuran double
  cout << "sizeof(char): " << sizeof(char) << "\n";       // ukuran char
  cout << "sizeof(bool): " << sizeof(bool) << "\n";       // ukuran bool
  return 0;
}
